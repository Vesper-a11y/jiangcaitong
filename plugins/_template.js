/* 酱菜通插件模板 —— 复制这个文件，改掉里面的字就是一个插件。
 *
 * 规则（不做也没关系，但别指望它能干更多）：
 *   · 卡片只有五样：名字、标签、两个数、一句状态、一个按钮。
 *     App 负责画，排版和内置的四个组件完全一致 —— 插件塞不进 HTML，也改不了别处。
 *   · 能用的只有这几样（都是只读的，改了也不会影响 App 别处）：
 *       plugin.toast(文字)      弹一句提示
 *       plugin.data(键, 值)     存 / 读自己的数据（只写一个参数就是读）
 *       plugin.week()           现在是第几周
 *       plugin.total()          这学期一共几周
 *       plugin.today()          今天 { m, d, w, text }，text 形如「11月28日 周六」
 *   · 不联网。要联网取数据的话，先提需求，我加到 App 里再给你用。
 *
 * 写好后发到交流群（QQ 群 1135309695），或者在 GitHub 提 Issue，
 * 我看过之后传到 plugins/<id>/<版本>.js，再在 index.json 里加一行就上架了。
 */
plugin({
  name: '插件名字',          // 最多 20 字，显示在卡片左上
  tag: '六个字内',            // 卡片上的小标签
  stats: () => [
    { k: '左边', v: '—' },    // 最多两个数，v 写成 '—' 就是「暂时没有」
    { k: '右边', v: '—' }
  ],
  state: () => '● 卡片底部那句话',
  action: {
    label: '去看看',          // 右下那个按钮的字
    run() {
      const n = (plugin.data('n') || 0) + 1;
      plugin.data('n', n);
      plugin.toast('点了 ' + n + ' 次，第 ' + plugin.week() + ' 周');
    }
  }
});
